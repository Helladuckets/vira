def _next_due(r):
    if not r.get("enabled"):
        return None
    now = datetime.now().astimezone()
    if r.get("daily_at"):
        try:
            hh, mm = str(r["daily_at"]).split(":")
            gate = now.replace(hour=int(hh), minute=int(mm), second=0,
                               microsecond=0)
        except (ValueError, AttributeError):
            return None
        if routines.is_due(r, now):
            return now
        return gate if now < gate else gate + timedelta(days=1)
    hours = float(r.get("every_hours") or 0)
    if hours <= 0:
        return None
    last = r.get("last_run")
    if not last:
        return now
    try:
        last_dt = datetime.fromisoformat(last).astimezone()
    except ValueError:
        return now
    due = last_dt + timedelta(hours=hours)
    return max(due, now) if due > now else now


def engine_of(r) -> str:
    """internal | session | circuit — the three ways a loop can run."""
    if r.get("kind") == "circuit":
        return "circuit"
    token = (r.get("prompt") or "").strip()
    if token in TOKENS and token not in COMPOSERS:
        return "internal"
    return "session"


def facts(r) -> list:
    """The labeled facts, in reading order. Each {label, value, tone}."""
    engine = engine_of(r)
    cad = ("daily at " + r["daily_at"]) if r.get("daily_at") else (
        f"every {_hours(r.get('every_hours'))}" if r.get("every_hours")
        else "no cadence set")
    nxt = _next_due(r)
    if not r.get("enabled"):
        nxt_label = "paused"
    elif routines.is_due(r):
        nxt_label = "due now — the next tick will run it"
    else:
        nxt_label = _when(nxt) if nxt else "unknown"
    rows = [
        {"label": "Runs", "value": cad},
        {"label": "Next", "value": nxt_label,
         "tone": "dim" if not r.get("enabled") else ""},
        {"label": "Engine", "value": {
            "internal": "in process — no model call, no cost",
            "circuit": "a multi-stage recipe",
            "session": "a live agent session, with a terminal",
        }[engine]},
    ]
    if engine == "session":
        rows.append({"label": "Permission",
                     "value": _mode_label(r.get("mode"))})
    rows.append({"label": "Writes", "value": effect_of(r)})
    rows.append({"label": "Tells you",
                 "value": ("an iMessage when a run finishes"
                           if r.get("notify") else
                           "nothing — it runs silently")})
    last = []
    if r.get("last_run"):
        last.append(_when(_parse(r["last_run"])))
    if r.get("last_status"):
        last.append(r["last_status"])
    rows.append({"label": "Last run",
                 "value": " · ".join(last) if last else "never run",
                 "tone": "warn" if "skip" in (r.get("last_status") or "")
                 else ""})
    return rows


def effect_of(r) -> str:
    token = (r.get("prompt") or "").strip()
    if token in EFFECTS:
        return EFFECTS[token]
    if r.get("kind") in KIND_EFFECTS:
        return KIND_EFFECTS[r["kind"]]
    if r.get("kind") == "circuit":
        return "whatever its recipe's stages write."
    return ("whatever the prompt asks for — an ordinary session, so it can "
            "touch anything a session can.")


