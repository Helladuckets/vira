def _part(pid, title, text, *, kind, lang="text", note="", editable=False,
          module="", symbol="", shared=False):
    body = text or ""
    return {"id": pid, "title": title, "note": note, "kind": kind,
            "lang": lang, "editable": bool(editable), "shared": bool(shared),
            "module": module, "symbol": symbol,
            "path": _rel(_src_path(module)) if module else "",
            "lines": len(body.splitlines()),
            "sha": hashlib.sha256(body.encode("utf-8")).hexdigest()[:12],
            "text": body}


def _code_part(pid, module, symbol, title, note, shared=False):
    try:
        text = read_symbol(module, symbol)
    except (ValueError, OSError) as e:      # a renamed function, honestly
        return _part(pid, title, "", kind="missing",
                     note=f"could not be located in the source: {e}")
    return _part(pid, title, text, kind="code", lang="python", note=note,
                 editable=True, module=module, symbol=symbol, shared=shared)


def _composed(token):
    """The prompt a composing token produces right now, or None."""
    try:
        if token == "__module_map__":
            from . import modulemap
            return modulemap.refresh_prompt()
        if token == "__room_scout__":
            from . import readingroom
            return readingroom.refresh_all_prompt() or ""
    except Exception as e:  # noqa: BLE001 — a preview never breaks the panel
        return f"(could not compose right now: {e})"
    return None


def parts(r) -> list:
    """Every piece of one routine, loop-specific first."""
    out = []
    kind = r.get("kind")
    token = (r.get("prompt") or "").strip()

    if kind == "muse":
        out.append(_code_part(
            "code:muse", "routines", "_muse_prompt",
            "How the muse's prompt is built",
            "Composed fresh at every dispatch, so the backlog it is told "
            "not to duplicate is always the current one. This is the "
            "editable half — the text below is its output."))
        try:
            out.append(_part("derived:muse", "The prompt it will send today",
                             routines._muse_prompt(), kind="derived",
                             note="Generated by the function above. Shown "
                                  "in full so nothing is hidden; edit the "
                                  "function to change it."))
        except Exception:  # noqa: BLE001
            pass
    elif kind == "circuit":
        out.append(_part("field:circuit", "The recipe it runs",
                         r.get("circuit_id") or "(none chosen)",
                         kind="derived",
                         note="Circuits are edited in Work · Dispatch · "
                              "Recipes, where each stage has its own tray."))
    elif token in TOKENS:
        composes = token in COMPOSERS
        lead = ("Composed fresh at every dispatch and handed to a session."
                if composes else
                "Runs in process, right here in the server. No model call, "
                "no cost, and it works on a machine with no AI connected.")
        for i, (module, symbol, title, note) in enumerate(TOKENS[token]):
            out.append(_code_part(
                f"code:token{i or ''}", module, symbol, title,
                (lead + (" " + note if note else "")) if i == 0 else note))
        if composes:
            text = _composed(token)
            if text is not None:
                out.append(_part(
                    "derived:token", "The prompt it would send right now",
                    text or "(nothing to do — this loop would no-op)",
                    kind="derived",
                    note="Generated by the function above."))
    else:
        out.append(_part("field:prompt", "The prompt this loop runs",
                         r.get("prompt") or "", kind="field", editable=True,
                         note="Sent verbatim to a fresh session at every "
                              "run. Plain text — edit it freely."))

    for module, symbol, title, note in SHARED:
        out.append(_code_part(f"shared:{module}.{symbol}", module, symbol,
                              title, note, shared=True))
    return out


