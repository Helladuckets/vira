def _src_path(module: str) -> Path:
    """The file for a server module name, validated to live in this
    checkout's server/ directory. The only door to the filesystem here."""
    if not re.fullmatch(r"[a-z_][a-z0-9_]{0,40}", module or ""):
        raise ValueError(f"bad module name: {module!r}")
    p = (SRC_DIR / f"{module}.py").resolve()
    if p.parent != SRC_DIR.resolve() or not p.is_file():
        raise ValueError(f"no such module: {module}")
    return p


def _find(tree: ast.AST, symbol: str):
    """The AST node for a dotted symbol ('refresh', 'Scheduler.tick')."""
    node = tree
    for name in symbol.split("."):
        body = getattr(node, "body", None)
        if body is None:
            return None
        node = next(
            (n for n in body
             if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef,
                               ast.ClassDef)) and n.name == name), None)
        if node is None:
            return None
    return node


def locate(module: str, symbol: str):
    """(path, first_line, last_line) for a symbol, read from the file's
    CURRENT text. Deliberately not inspect.getsourcelines: an edited
    module is stale in memory until a restart, and the range a write
    splices over has to describe the file on disk, not the import."""
    path = _src_path(module)
    text = path.read_text(encoding="utf-8")
    node = _find(ast.parse(text), symbol)
    if node is None:
        raise ValueError(f"{module}.{symbol} not found")
    first = min([node.lineno] + [d.lineno for d in
                                 getattr(node, "decorator_list", [])])
    return path, first, node.end_lineno


def read_symbol(module: str, symbol: str):
    path, a, b = locate(module, symbol)
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    return "".join(lines[a - 1:b])


def _rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


