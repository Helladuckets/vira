"""Under the hood — what a standing loop actually IS, and editing it.

A routine's row in Work · Dispatch · Schedules said its name, its cadence,
and one sentence the seed happened to carry. Everything that decides what
it DOES — the prompt composed at dispatch, the in-process function an
internal token resolves to, the scheduler that fires it — lived only in
the source. So the panel a stranger meets during onboarding described
five loops it could not open.

This module opens them. ``hood(r)`` resolves one routine into three
things, all DERIVED at read time so none of them can drift from the code
they describe:

  facts   the trigger, the engine, the blast radius — what it writes,
          whether it costs a model call, what it tells you afterwards.
  steps   how the loop actually fires, in order, in plain English.
  parts   the FULL text of every piece: the prompt (stored, or composed
          live), the Python function an internal token runs, and the
          shared scheduler machinery underneath all of them.

EDITING. A part is one of three kinds and each is written back a
different way:

  field   a routine field (name, prompt, cadence, description) — goes
          through ``routines.save_routine``, the same validated path the
          form uses. Takes effect on the next tick.
  code    a Python function in this checkout. Spliced back over the
          function's CURRENT line range, which is re-derived from the
          file's AST at write time rather than trusted from the read —
          two edits in a row shift every line under them, and a stale
          range would write into the middle of a neighbour. The merged
          file must PARSE and must still define the symbol; a file that
          fails either is never written. Needs a restart.
  derived a live composition (the muse's prompt, the room sweep) — shown
          in full so you can see what actually goes to the model, but not
          editable HERE: it is generated by the code part beside it, and
          an edit would be overwritten by the next run.

Every code write snapshots the whole file to ``data/backups/code/`` first
(that is what ``revert`` restores), and ``restore_shipped`` goes further
back, to the version in git. Editing is allowed on every instance — see
``writable`` for why a test clone is not the exception it looks like —
but only a supervised one offers the restart that loads the change.
"""
