def _mode_label(mode):
    return {
        "manual": "manual — every risky call asks you first",
        "acceptEdits": "accept edits — file edits land unasked, commands ask",
        "bypassPermissions": "bypass — nothing asks (the default)",
    }.get(_norm_mode(mode), "bypass — nothing asks (the default)")


def _norm_mode(mode):
    try:
        from . import session
        return session.norm_mode(mode, "bypassPermissions")
    except Exception:  # noqa: BLE001
        return mode or "bypassPermissions"


def _hours(h):
    try:
        h = float(h or 0)
    except (TypeError, ValueError):
        return "?"
    if h <= 0:
        return "?"
    if h % 24 == 0:
        d = int(h // 24)
        return "24 hours" if d == 1 else f"{d} days"
    return f"{h:g} hours"


def _parse(s):
    try:
        return datetime.fromisoformat(s).astimezone()
    except (TypeError, ValueError):
        return None


def _when(dt):
    if not dt:
        return "unknown"
    now = datetime.now().astimezone()
    delta = (dt - now).total_seconds()
    ago = delta < 0
    secs = abs(delta)
    if secs < 90:
        return "just now" if ago else "in under a minute"
    for size, name in ((3600, "minute"), (86400, "hour"), (86400 * 7, "day")):
        if secs < size:
            step = size // 60 if name == "minute" else (
                3600 if name == "hour" else 86400)
            n = int(secs // step)
            unit = name + ("" if n == 1 else "s")
            return f"{n} {unit} ago" if ago else f"in {n} {unit}"
    return dt.strftime("%-d %b, %H:%M") if not _is_win() \
        else dt.strftime("%d %b, %H:%M")


def _is_win():
    from . import settings
    return settings.IS_WIN


def hood(r) -> dict:
    ps = parts(r)
    # Per-FILE, not per-part: two parts of routines.py share one backup
    # stack, so a revert offered on one is the same revert offered on the
    # other. Answering it once keeps the two buttons from disagreeing.
    files = {p["module"]: state(p["module"]) for p in ps if p["module"]}
    return {"id": r["id"], "name": r.get("name") or r["id"],
            "engine": engine_of(r), "kind": r.get("kind"),
            "description": r.get("description") or "",
            "facts": facts(r), "steps": steps(r), "parts": ps,
            "files": files, "writable": writable()}


# ---------------------------------------------------------------- writing

def writable() -> dict:
    """Whether source edits are allowed here, and WHICH checkout they land
    in. Deliberately allowed on a test instance and in a sandbox, unlike
    the outbound guards: those refusals exist because a clone must never
    act on the WORLD, and its own source is not the world. A branch
    instance edits the branch it is serving — which is what a branch
    instance is for — and `branch.sh merge` preflights a clean tree, so a
    stray edit there blocks its own merge loudly rather than riding it.

    What a non-live instance does NOT get is the restart button: it has no
    supervisor to come back from an exit."""
    root = str(ROOT)
    if os.environ.get("VIRA_PASSIVE"):
        return {"ok": True, "root": root, "restart": False,
                "reason": f"Test instance — edits land in this branch's own "
                          f"checkout ({root}), not in live Vira."}
    if os.environ.get("VIRA_SANDBOX"):
        return {"ok": True, "root": root, "restart": False,
                "reason": f"Sandbox — edits land in {root}."}
    return {"ok": True, "root": root, "restart": True, "reason": ""}


class EditError(ValueError):
    """A refused edit. Carries the reason the panel shows verbatim."""


def _guard():
    w = writable()
    if not w["ok"]:
        raise EditError(w["reason"])


def _backup(path: Path) -> Path:
    """Snapshot the file before it is touched.

    The name ALWAYS carries a zero-padded sequence, never only on a
    collision: revert reads `sorted(...)[-1]` as "the newest", and a bare
    `<stamp>.py` sorts AFTER `<stamp>-1.py` ('-' is 45, '.' is 46), so two
    saves in the same second would have handed revert the older file. Every
    name shaped alike keeps lexical order and chronological order the same
    thing."""
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S")
    n = 0
    dest = BACKUP_DIR / f"{path.stem}.{stamp}-{n:03d}.py"
    while dest.exists():
        n += 1
        dest = BACKUP_DIR / f"{path.stem}.{stamp}-{n:03d}.py"
    dest.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
    old = sorted(BACKUP_DIR.glob(f"{path.stem}.*.py"))
    for stale in old[:-KEEP_BACKUPS]:
        try:
            stale.unlink()
        except OSError:
            pass
    return dest


def backups(module: str) -> list:
    """Newest first: what revert has to offer for this file."""
    path = _src_path(module)
    out = []
    for p in sorted(BACKUP_DIR.glob(f"{path.stem}.*.py"), reverse=True):
        try:
            out.append({"file": p.name,
                        "at": datetime.fromtimestamp(
                            p.stat().st_mtime, timezone.utc).isoformat(
                                timespec="seconds")})
        except OSError:
            pass
    return out


def _write(path: Path, text: str):
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def write_symbol(module: str, symbol: str, text: str) -> dict:
    """Splice new source over a function, or refuse and change nothing.

    Three checks, in this order, because each one only means anything if
    the one before it passed: the replacement is a plausible size; the
    MERGED file parses; and the symbol still exists in it afterwards. A
    replacement that parses on its own can still break the file it lands
    in (indentation, a stray dedent), which is why the parse is of the
    whole merged text and never of the fragment."""
    _guard()
    if len(text.encode("utf-8")) > MAX_EDIT_BYTES:
        raise EditError("that is too large to be one function")
    path, a, b = locate(module, symbol)      # re-derived NOW, never trusted
    original = path.read_text(encoding="utf-8")
    lines = original.splitlines(keepends=True)
    body = text if text.endswith("\n") else text + "\n"
    merged = "".join(lines[:a - 1]) + body + "".join(lines[b:])
    if merged == original:
        return {"changed": False, "path": _rel(path)}
    try:
        tree = ast.parse(merged)
    except SyntaxError as e:
        # the parser counts lines in the MERGED file, which means nothing to
        # someone reading the one function they just typed
        n = e.lineno or 0
        body_lines = len(body.splitlines())
        where = (f"line {n - a + 1} of what you typed"
                 if a <= n < a + body_lines else f"line {n} of the file")
        raise EditError(f"that would not parse — {where}: {e.msg}. "
                        "Nothing was written.") from None
    if _find(tree, symbol) is None:
        raise EditError(
            f"the replacement no longer defines {symbol} — rename it back, "
            "or make the change in a session instead. Nothing was written.")
    backup = _backup(path)
    _write(path, merged)
    return {"changed": True, "path": _rel(path), "backup": backup.name,
            "restart": writable()["restart"]}


def revert(module: str) -> dict:
    """Undo the last edit to this file by restoring its newest backup —
    which is the file as it stood BEFORE that edit, since the snapshot is
    taken on the way in. Consumes the snapshot, so pressing revert twice
    steps back twice."""
    _guard()
    path = _src_path(module)
    snaps = sorted(BACKUP_DIR.glob(f"{path.stem}.*.py"), reverse=True)
    if not snaps:
        raise EditError("there is no backup to go back to")
    text = snaps[0].read_text(encoding="utf-8")
    try:
        ast.parse(text)
    except SyntaxError as e:                 # a snapshot should always parse
        raise EditError(f"that backup is unusable: {e.msg}") from None
    _write(path, text)
    try:
        snaps[0].unlink()
    except OSError:
        pass
    return {"path": _rel(path), "from": snaps[0].name,
            "restart": writable()["restart"], "remaining": len(snaps) - 1}


def shipped(module: str):
    """The committed version of this file, or None when git cannot say."""
    path = _src_path(module)
    try:
        out = gitutil.git(ROOT, "show", f"HEAD:{_rel(path)}")
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout if out.returncode == 0 else None


def modified(module: str) -> bool:
    ship = shipped(module)
    if ship is None:
        return False
    return ship != _src_path(module).read_text(encoding="utf-8")


def restore_shipped(module: str) -> dict:
    """Back to the version in git — the way out when several edits have
    piled up and stepping back one at a time is not what you want."""
    _guard()
    ship = shipped(module)
    if ship is None:
        raise EditError("git cannot tell me what shipped for this file")
    path = _src_path(module)
    if ship == path.read_text(encoding="utf-8"):
        return {"path": _rel(path), "changed": False}
    _backup(path)
    _write(path, ship)
    return {"path": _rel(path), "changed": True,
            "restart": writable()["restart"]}


def apply_part(r, part_id: str, text: str) -> dict:
    """Write one part back. The routine's own fields go through
    save_routine — the validated path the form already uses — so a
    cadence typed here is checked exactly as one typed there."""
    _guard()
    found = next((p for p in parts(r) if p["id"] == part_id), None)
    if not found:
        raise EditError("unknown part")
    if not found["editable"]:
        raise EditError(f"{found['title']} is generated — "
                        "edit the code that produces it instead")
    if found["kind"] == "code":
        return write_symbol(found["module"], found["symbol"], text)
    field = part_id.split(":", 1)[1]
    routines.save_routine({field: text}, rid=r["id"])
    return {"changed": True, "field": field, "restart": False}


